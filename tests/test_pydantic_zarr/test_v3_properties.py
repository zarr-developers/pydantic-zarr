"""
Property-based tests for Zarr V3 metadata document validation.

Two independent implementations of the Zarr V3 spec are available here:
zarr-python's metadata layer and ``zarr-metadata`` (which `ArraySpec`
delegates its document validation to). That solves the oracle problem
property-based testing usually has: the property under test is *agreement*
between the implementations, not correctness against hand-written answers.

- Documents generated by zarr-python's own hypothesis strategies must be
  accepted by `ArraySpec`, and specs built from an independent document
  generator must produce ``model_dump()`` output that zarr-python parses.
- Single invalidating mutations of a valid document must be refused.
- Equal fill values in different spellings must compare alike.
"""

from __future__ import annotations

import importlib.util
import json
from typing import TYPE_CHECKING, Any

import pytest
from hypothesis import HealthCheck, given, settings
from hypothesis import strategies as st
from packaging.version import Version
from pydantic import ValidationError

from pydantic_zarr.core import tuplify_json
from pydantic_zarr.v3 import ArraySpec, GroupSpec

from .conftest import ZARR_PYTHON_VERSION

if TYPE_CHECKING:
    from collections.abc import Callable

ZARR_AVAILABLE = importlib.util.find_spec("zarr") is not None

PROPERTY_SETTINGS = settings(
    max_examples=75,
    deadline=None,
    # one deterministic run per test: every CI matrix cell checks the same
    # examples, so a failure reproduces everywhere instead of depending on
    # which cell drew the failing seed
    derandomize=True,
    # the strategies are module-level and stateless; the suppression keeps
    # hypothesis from flagging slow first-example data generation on CI
    suppress_health_check=[HealthCheck.too_slow],
)

# fill value strategies per data type, in the JSON spellings the spec allows
_FLOAT_FILLS = st.one_of(
    st.floats(allow_nan=False, allow_infinity=False, width=16),
    st.sampled_from(["NaN", "Infinity", "-Infinity"]),
)
_DTYPES_AND_FILLS: dict[str, st.SearchStrategy[object]] = {
    "bool": st.booleans(),
    "int8": st.integers(-(2**7), 2**7 - 1),
    "int16": st.integers(-(2**15), 2**15 - 1),
    "int32": st.integers(-(2**31), 2**31 - 1),
    "int64": st.integers(-(2**63), 2**63 - 1),
    "uint8": st.integers(0, 2**8 - 1),
    "uint16": st.integers(0, 2**16 - 1),
    "uint32": st.integers(0, 2**32 - 1),
    "uint64": st.integers(0, 2**64 - 1),
    "float16": _FLOAT_FILLS,
    "float32": _FLOAT_FILLS,
    "float64": _FLOAT_FILLS,
    "complex64": st.tuples(_FLOAT_FILLS, _FLOAT_FILLS),
    "complex128": st.tuples(_FLOAT_FILLS, _FLOAT_FILLS),
}

_BYTES_CODEC = {"name": "bytes", "configuration": {"endian": "little"}}
_BYTES_TO_BYTES: st.SearchStrategy[dict[str, Any]] = st.sampled_from(
    [
        {"name": "gzip", "configuration": {"level": 1}},
        {"name": "zstd", "configuration": {"level": 0, "checksum": False}},
        {"name": "crc32c"},
    ]
)


@st.composite
def array_documents(draw: st.DrawFn) -> dict[str, Any]:
    """
    Keyword arguments for a valid `ArraySpec`, independent of zarr-python.

    The documents cover every core numeric data type with a matching fill
    value (non-finite floats in their string spellings included), shapes of
    rank 1-3 with zero-length dimensions allowed, aligned chunk shapes, both
    chunk key encodings, an optional bytes -> bytes codec tail, and optional
    dimension names.
    """
    data_type = draw(st.sampled_from(sorted(_DTYPES_AND_FILLS)))
    fill_value = draw(_DTYPES_AND_FILLS[data_type])
    shape = tuple(draw(st.lists(st.integers(0, 8), min_size=1, max_size=3)))
    # chunk lengths are at least 1, along zero-length dimensions too
    chunk_shape = tuple(draw(st.integers(1, max(dim, 1))) for dim in shape)
    codecs: list[dict[str, Any]] = [_BYTES_CODEC]
    if draw(st.booleans()):
        codecs.append(draw(_BYTES_TO_BYTES))
    separator = draw(st.sampled_from([".", "/"]))
    encoding_name = draw(st.sampled_from(["default", "v2"]))
    dimension_names = draw(
        st.none() | st.lists(st.text(max_size=3), min_size=len(shape), max_size=len(shape))
    )
    return {
        "attributes": {},
        "shape": shape,
        "data_type": data_type,
        "chunk_grid": {"name": "regular", "configuration": {"chunk_shape": chunk_shape}},
        "chunk_key_encoding": {"name": encoding_name, "configuration": {"separator": separator}},
        "fill_value": fill_value,
        "codecs": tuple(codecs),
        "dimension_names": dimension_names,
    }


@pytest.mark.skipif(not ZARR_AVAILABLE, reason="zarr is required for this test")
@pytest.mark.filterwarnings("ignore:The data type :FutureWarning")
@pytest.mark.filterwarnings("ignore:The structured dtype is converted to a packed field layout")
@PROPERTY_SETTINGS
@given(data=st.data())
def test_zarr_generated_metadata_accepted(data: st.DataObject) -> None:
    """
    Agreement with zarr-python, reading direction: every V3 array metadata
    document zarr-python's own strategies generate is accepted by `ArraySpec`,
    round-trips through `model_dump` unchanged, is alike itself, and dumps to
    a document zarr-python parses back.
    """
    from zarr.core.metadata import ArrayV3Metadata
    from zarr.testing.strategies import array_metadata

    meta = data.draw(array_metadata(zarr_formats=st.just(3)))
    if ZARR_PYTHON_VERSION < Version("3.1.0"):
        # zarr 3.0's to_dict returns non-JSON values (e.g. the DataType enum
        # for data_type); encode through its JSON encoder, as from_zarr does
        from zarr.core.metadata.v3 import V3JsonEncoder  # type: ignore[attr-defined]

        document = tuplify_json(json.loads(json.dumps(meta.to_dict(), cls=V3JsonEncoder)))
    else:
        document = tuplify_json(meta.to_dict())
    spec: ArraySpec[Any] = ArraySpec(**document)
    assert ArraySpec(**spec.model_dump()) == spec
    assert spec.like(spec)
    # ...and zarr-python accepts what the spec emits
    ArrayV3Metadata.from_dict(spec.model_dump())


@pytest.mark.skipif(not ZARR_AVAILABLE, reason="zarr is required for this test")
@PROPERTY_SETTINGS
@given(document=array_documents())
def test_accepted_documents_parse_in_zarr(document: dict[str, Any]) -> None:
    """
    Agreement with zarr-python, writing direction: a document from this
    module's own generator that `ArraySpec` accepts dumps to metadata that
    zarr-python parses. This generator is independent of zarr-python's, so it
    can catch `ArraySpec` being looser than zarr.
    """
    from zarr.core.metadata import ArrayV3Metadata

    spec: ArraySpec[Any] = ArraySpec(**document)
    ArrayV3Metadata.from_dict(spec.model_dump())


@PROPERTY_SETTINGS
@given(document=array_documents())
def test_documents_round_trip(document: dict[str, Any]) -> None:
    """
    For every document the generator produces, `ArraySpec` accepts it, the
    spec round-trips through `model_dump`, and `like` is reflexive.
    """
    spec: ArraySpec[Any] = ArraySpec(**document)
    assert ArraySpec(**spec.model_dump()) == spec
    assert spec.like(spec)


_NAN_SPELLINGS: dict[str, tuple[object, ...]] = {
    "float16": (float("nan"), "NaN", "0x7e00"),
    "float32": (float("nan"), "NaN", "0x7fc00000"),
    "float64": (float("nan"), "NaN", "0x7ff8000000000000"),
}


@PROPERTY_SETTINGS
@given(document=array_documents(), data=st.data())
def test_fill_value_spellings_alike(document: dict[str, Any], data: st.DataObject) -> None:
    """
    Specs that differ only in the spelling of one float NaN fill value (the
    float itself, the string "NaN", or the hexadecimal byte form) are alike.
    """
    dtype = data.draw(st.sampled_from(sorted(_NAN_SPELLINGS)))
    spellings = _NAN_SPELLINGS[dtype]
    document = {**document, "data_type": dtype}
    specs: list[ArraySpec[Any]] = [
        ArraySpec.model_validate({**document, "fill_value": spelling}) for spelling in spellings
    ]
    for other in specs[1:]:
        assert specs[0].like(other)
        assert other.like(specs[0])


def _mutate_chunk_rank(document: dict[str, Any]) -> dict[str, Any]:
    grid = document["chunk_grid"]
    chunk_shape = (*grid["configuration"]["chunk_shape"], 1)
    return {
        **document,
        "chunk_grid": {"name": "regular", "configuration": {"chunk_shape": chunk_shape}},
    }


def _mutate_fill_dtype_mismatch(document: dict[str, Any]) -> dict[str, Any]:
    return {**document, "data_type": "int8", "fill_value": "NaN"}


def _mutate_duplicate_bytes_codec(document: dict[str, Any]) -> dict[str, Any]:
    return {**document, "codecs": (_BYTES_CODEC, _BYTES_CODEC)}


def _mutate_illegal_codec_name(document: dict[str, Any]) -> dict[str, Any]:
    return {**document, "codecs": (_BYTES_CODEC, {"name": "Not/A/Name"})}


def _mutate_zero_chunk_length(document: dict[str, Any]) -> dict[str, Any]:
    chunk_shape = (0,) * len(document["shape"])
    return {
        **document,
        "chunk_grid": {"name": "regular", "configuration": {"chunk_shape": chunk_shape}},
    }


@pytest.mark.parametrize(
    "mutate",
    [
        _mutate_chunk_rank,
        _mutate_fill_dtype_mismatch,
        _mutate_duplicate_bytes_codec,
        _mutate_illegal_codec_name,
        _mutate_zero_chunk_length,
    ],
    ids=lambda fn: fn.__name__.removeprefix("_mutate_"),
)
@PROPERTY_SETTINGS
@given(document=array_documents())
def test_invalid_mutations_rejected(
    mutate: Callable[[dict[str, Any]], dict[str, Any]], document: dict[str, Any]
) -> None:
    """
    Applying one invalidating mutation to any valid document makes
    `ArraySpec` refuse it, whatever the rest of the document holds.
    """
    with pytest.raises(ValidationError):
        ArraySpec(**mutate(document))


@pytest.mark.skipif(not ZARR_AVAILABLE, reason="zarr is required for this test")
@PROPERTY_SETTINGS
@given(data=st.data(), document=array_documents())
def test_zarr_node_names_accepted_as_members(data: st.DataObject, document: dict[str, Any]) -> None:
    """
    Agreement on node names: every name zarr-python's `node_names` strategy
    generates is a valid `GroupSpec` member name.
    """
    from zarr.testing.strategies import node_names

    name = data.draw(node_names)
    array: ArraySpec[Any] = ArraySpec(**document)
    group: GroupSpec[Any, Any] = GroupSpec(attributes={}, members={name: array})
    assert tuple(group.members) == (name,)
